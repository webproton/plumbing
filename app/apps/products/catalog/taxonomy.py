VERTICALS = {v.key: v for v in (PLUMBING, TOOLS, BIKES, FURNITURE)}


# «Общие» категории — только если ничего конкретнее не нашлось («велосипедний шолом» → Шоломи, не Велосипеди)
GENERIC = {"zmishuvachi", "kotly", "filtry", "velosypedy-dorosli", "dushovi-systemy"}


def classify(text: str, vertical: Vertical) -> tuple[Section, Leaf] | None:
    """Категория с самым длинным (конкретным) совпавшим словом; при равенстве — та, что выше в списке."""
    low = f" {text.lower()} "
    best, best_score = None, -1000
    for section, leaf in vertical.leaves:
        for keyword in leaf.keywords:
            if keyword in low:
                score = len(keyword) - (100 if leaf.slug in GENERIC else 0)
                if score > best_score:
                    best, best_score = (section, leaf), score
    return best
